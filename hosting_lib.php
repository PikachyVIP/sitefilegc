<?php
declare(strict_types=1);

require_once __DIR__ . '/bootstrap.php';

/**
 * Public photo/video hosting helpers. Rows live in hosted_media; a row either
 * points at an existing files row (is_copy=false) or owns its uploaded file
 * (is_copy=true), which is the only case where expiry/delete may unlink it.
 */

/**
 * The deploy workflow replaces code but does not run schema.sql. Create the
 * table on the first hosting request so a fresh deploy cannot 500; schema.sql
 * stays the source of truth for a full install.
 */
function gc_media_ensure_schema(PDO $pdo): void
{
    static $checked = false;
    if ($checked) {
        return;
    }
    $exists = $pdo->query("SELECT to_regclass('public.hosted_media')")->fetchColumn();
    if (!$exists) {
        $pdo->exec(
            "CREATE TABLE IF NOT EXISTS hosted_media (
                id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                token         text NOT NULL UNIQUE,
                file_id       integer REFERENCES files (id) ON DELETE SET NULL,
                filename      text NOT NULL,
                original_name text NOT NULL,
                mime_type     text NOT NULL DEFAULT 'application/octet-stream',
                file_size     bigint NOT NULL DEFAULT 0,
                uploader_id   integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
                is_copy       boolean NOT NULL DEFAULT false,
                created_at    timestamp without time zone NOT NULL DEFAULT now(),
                expires_at    timestamp without time zone,
                views         integer NOT NULL DEFAULT 0
            )"
        );
        $pdo->exec('CREATE INDEX IF NOT EXISTS hosted_media_expires_idx ON hosted_media (expires_at)');
        $pdo->exec('CREATE INDEX IF NOT EXISTS hosted_media_uploader_idx ON hosted_media (uploader_id, created_at DESC)');
    }
    $checked = true;
}

function gc_media_token(): string
{
    return bin2hex(random_bytes(16));
}

function gc_media_direct_name(string $originalName, string $mime): string
{
    $ext = strtolower(pathinfo($originalName, PATHINFO_EXTENSION));
    $ext = preg_replace('/[^a-z0-9]/', '', $ext) ?? '';
    $fallback = [
        'image/jpeg' => 'jpg',
        'image/png' => 'png',
        'image/gif' => 'gif',
        'image/webp' => 'webp',
        'image/bmp' => 'bmp',
        'video/mp4' => 'mp4',
        'video/webm' => 'webm',
        'video/ogg' => 'ogg',
    ];
    if ($ext === '' || strlen($ext) > 8) {
        $ext = $fallback[strtolower(trim(explode(';', $mime)[0]))] ?? 'bin';
    }

    $base = pathinfo($originalName, PATHINFO_FILENAME);
    $base = preg_replace('/[^A-Za-z0-9._-]+/', '-', $base) ?? '';
    $base = trim($base, '.-_');
    if ($base === '') {
        $base = 'media';
    }
    $base = substr($base, 0, 80);

    return $base . '.' . $ext;
}

function gc_media_find(PDO $pdo, string $token): ?array
{
    $token = strtolower(trim($token));
    if (preg_match('/^[a-f0-9]{32}$/', $token) !== 1) {
        return null;
    }
    $statement = $pdo->prepare(
        'SELECT id, token, file_id, filename, original_name, mime_type, file_size,
                uploader_id, is_copy, created_at, expires_at, views
         FROM hosted_media WHERE token = ?'
    );
    $statement->execute([$token]);

    return $statement->fetch() ?: null;
}

function gc_media_page_url(string $token): string
{
    return gc_base_url() . '/hosting_view.php?t=' . rawurlencode($token);
}

function gc_media_direct_url(string $token, string $originalName, string $mime): string
{
    return gc_base_url() . '/hosting_file.php/' . rawurlencode($token)
        . '/' . rawurlencode(gc_media_direct_name($originalName, $mime));
}

/**
 * Remove expired hosted rows. Only uploaded copies are unlinked; links to
 * existing storage files must never delete the original.
 */
function gc_media_purge(PDO $pdo, string $uploadDir): void
{
    $statement = $pdo->query(
        'DELETE FROM hosted_media WHERE expires_at IS NOT NULL AND expires_at <= now()
         RETURNING filename, is_copy'
    );
    foreach ($statement->fetchAll() as $row) {
        if (!gc_bool_value($row['is_copy'] ?? false)) {
            continue;
        }
        $stored = (string) ($row['filename'] ?? '');
        if ($stored === '' || str_contains($stored, '/') || str_contains($stored, '\\')) {
            continue;
        }
        $path = $uploadDir . '/' . $stored;
        if (is_file($path)) {
            @unlink($path);
        }
    }
}

function gc_media_upload_dir(): string
{
    return __DIR__ . '/uploads';
}

/**
 * Normalize an allowed media MIME. Returns null for SVG/HTML/anything that a
 * public inline endpoint must not serve.
 */
function gc_media_mime(string $mime, string $name): ?string
{
    $kind = gc_preview_kind($mime, $name);
    if ($kind !== 'image' && $kind !== 'video') {
        return null;
    }

    $clean = strtolower(trim(explode(';', $mime)[0]));
    $ext = strtolower(pathinfo($name, PATHINFO_EXTENSION));
    $byExt = [
        'jpg' => 'image/jpeg', 'jpeg' => 'image/jpeg', 'png' => 'image/png',
        'gif' => 'image/gif', 'webp' => 'image/webp', 'bmp' => 'image/bmp',
        'mp4' => 'video/mp4', 'webm' => 'video/webm', 'ogv' => 'video/ogg', 'ogg' => 'video/ogg',
    ];
    $allowed = [
        'image/jpeg', 'image/png', 'image/gif', 'image/webp', 'image/bmp',
        'video/mp4', 'video/webm', 'video/ogg',
    ];
    if (in_array($clean, $allowed, true)) {
        return $clean;
    }

    $fallback = $byExt[$ext] ?? '';
    return in_array($fallback, $allowed, true) ? $fallback : null;
}

function gc_media_path(string $stored): ?string
{
    if ($stored === '' || str_contains($stored, '/') || str_contains($stored, '\\')) {
        return null;
    }
    $base = realpath(gc_media_upload_dir());
    $path = realpath(gc_media_upload_dir() . '/' . basename($stored));
    if ($base === false || $path === false || !str_starts_with($path, $base . DIRECTORY_SEPARATOR) || !is_file($path)) {
        return null;
    }

    return $path;
}
