-- Схема базы данных GCFiles для PostgreSQL 12+
--
-- Применение вручную:
--   psql -U gc_files -d gc_files -f schema.sql
-- Отдельного setup.php нет: файл идемпотентен и добавляет недостающие
-- таблицы и колонки к существующей базе.
--
-- Скрипт идемпотентный: повторный запуск ничего не ломает.
-- Важно: главный администратор — пользователь с id = 1 (см. admin.php).

BEGIN;

CREATE TABLE IF NOT EXISTS users (
    id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login    text NOT NULL UNIQUE,
    password text NOT NULL
);

CREATE TABLE IF NOT EXISTS tags (
    id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS user_tags (
    user_id integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    tag_id  integer NOT NULL REFERENCES tags (id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, tag_id)
);

CREATE TABLE IF NOT EXISTS admin_rights (
    user_id    integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    right_name text NOT NULL,
    PRIMARY KEY (user_id, right_name)
);

CREATE TABLE IF NOT EXISTS files (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    filename      text NOT NULL,
    original_name text NOT NULL,
    uploader_id   integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    is_pinned     boolean NOT NULL DEFAULT false,
    uploaded_at   timestamp without time zone NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS file_tags (
    file_id integer NOT NULL REFERENCES files (id) ON DELETE CASCADE,
    tag_id  integer NOT NULL REFERENCES tags (id) ON DELETE CASCADE,
    PRIMARY KEY (file_id, tag_id)
);

CREATE TABLE IF NOT EXISTS file_access (
    file_id integer NOT NULL REFERENCES files (id) ON DELETE CASCADE,
    user_id integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    PRIMARY KEY (file_id, user_id)
);

-- Приложения команды. У каждого свои каналы stable/beta и свои релизы.
CREATE TABLE IF NOT EXISTS apps (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug        text NOT NULL UNIQUE,
    name        text NOT NULL,
    description text NOT NULL DEFAULT '',
    is_active   boolean NOT NULL DEFAULT true,
    created_at  timestamp without time zone NOT NULL DEFAULT now()
);

-- Релизы приложений (источник данных для автообновления).
-- app_id может быть NULL у строк, загруженных старой админкой; читатели
-- считают такие строки релизами приложения по умолчанию.
CREATE TABLE IF NOT EXISTS app_releases (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_id        integer REFERENCES apps (id) ON DELETE SET NULL,
    version       text NOT NULL,
    channel       text NOT NULL DEFAULT 'stable',
    filename      text NOT NULL,
    original_name text NOT NULL,
    file_size     bigint NOT NULL DEFAULT 0,
    sha256        text NOT NULL DEFAULT '',
    notes         text NOT NULL DEFAULT '',
    is_mandatory  boolean NOT NULL DEFAULT false,
    is_active     boolean NOT NULL DEFAULT true,
    downloads     integer NOT NULL DEFAULT 0,
    published_at  timestamp without time zone NOT NULL DEFAULT now(),
    published_by  integer REFERENCES users (id) ON DELETE SET NULL
);

-- Миграция существующей базы: колонка, приложение по умолчанию и бэкфилл.
ALTER TABLE app_releases ADD COLUMN IF NOT EXISTS app_id integer REFERENCES apps (id) ON DELETE SET NULL;

INSERT INTO apps (slug, name, description) VALUES
    ('gc-twitch-manager', 'GC Twitch Manager', 'Клиент команды GC для Twitch: автообновление stable/beta.')
ON CONFLICT (slug) DO NOTHING;

UPDATE app_releases
SET app_id = (SELECT id FROM apps ORDER BY id LIMIT 1)
WHERE app_id IS NULL;

-- Старый уникальный ключ не даёт загрузить одну версию в два приложения.
ALTER TABLE app_releases DROP CONSTRAINT IF EXISTS app_releases_channel_version_key;
CREATE UNIQUE INDEX IF NOT EXISTS app_releases_app_channel_version_idx
    ON app_releases (app_id, channel, version)
    WHERE app_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS app_releases_app_idx
    ON app_releases (app_id, channel, published_at DESC, id DESC);

-- Заметки на главной странице: пишет админ, читают все вошедшие.
CREATE TABLE IF NOT EXISTS changelog (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version      text NOT NULL DEFAULT '',
    title        text NOT NULL,
    body         text NOT NULL DEFAULT '',
    category     text NOT NULL DEFAULT 'site',
    is_published boolean NOT NULL DEFAULT true,
    published_at timestamp without time zone NOT NULL DEFAULT now(),
    published_by integer REFERENCES users (id) ON DELETE SET NULL
);

-- Временные ссылки: строка живёт до expires_at, файл лежит в uploads/.
CREATE TABLE IF NOT EXISTS transfers (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token         text NOT NULL UNIQUE,
    filename      text NOT NULL,
    original_name text NOT NULL,
    mime_type     text NOT NULL DEFAULT 'application/octet-stream',
    file_size     bigint NOT NULL DEFAULT 0,
    uploader_id   integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    note          text NOT NULL DEFAULT '',
    created_at    timestamp without time zone NOT NULL DEFAULT now(),
    expires_at    timestamp without time zone NOT NULL,
    downloads     integer NOT NULL DEFAULT 0
);

-- Публичный хостинг фото/видео. is_copy=true — файл создан загрузкой сюда,
-- поэтому при удалении строки его можно удалить; false — ссылка на files.
CREATE TABLE IF NOT EXISTS hosted_media (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token         text NOT NULL UNIQUE,
    file_id       integer REFERENCES files (id) ON DELETE SET NULL,
    filename      text NOT NULL,
    original_name text NOT NULL,
    mime_type     text NOT NULL DEFAULT 'application/octet-stream',
    file_size     bigint NOT NULL DEFAULT 0,
    uploader_id   integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    is_copy       boolean NOT NULL DEFAULT false,
    created_at    timestamp without time zone NOT NULL DEFAULT now(),
    expires_at    timestamp without time zone,
    views         integer NOT NULL DEFAULT 0
);

-- Папки основного хранилища. parent_id = NULL — корень.
CREATE TABLE IF NOT EXISTS folders (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text NOT NULL,
    parent_id   integer REFERENCES folders (id) ON DELETE CASCADE,
    created_by  integer REFERENCES users (id) ON DELETE SET NULL,
    is_personal boolean NOT NULL DEFAULT false,
    created_at  timestamp without time zone NOT NULL DEFAULT now()
);

-- Личная папка: одно корневое дерево на пользователя, видимое только ему.
ALTER TABLE folders ADD COLUMN IF NOT EXISTS is_personal boolean NOT NULL DEFAULT false;

-- Теги папки: шаблон, который кнопкой «Синхронизировать» копируется всем файлам.
-- Сами по себе теги папки видимость не меняют — доступ к файлам по-прежнему дают их теги.
CREATE TABLE IF NOT EXISTS folder_tags (
    folder_id  integer NOT NULL REFERENCES folders (id) ON DELETE CASCADE,
    tag_id     integer NOT NULL REFERENCES tags (id) ON DELETE CASCADE,
    created_at timestamp without time zone NOT NULL DEFAULT now(),
    PRIMARY KEY (folder_id, tag_id)
);

CREATE INDEX IF NOT EXISTS folder_tags_tag_idx ON folder_tags (tag_id);

-- Старая модель прав папок (до тегов) больше не используется.
DROP TABLE IF EXISTS folder_rights;

-- Метаданные файла: папка, размер и MIME. У старых строк они пустые.
ALTER TABLE files ADD COLUMN IF NOT EXISTS folder_id integer REFERENCES folders (id) ON DELETE SET NULL;
ALTER TABLE files ADD COLUMN IF NOT EXISTS file_size bigint;
ALTER TABLE files ADD COLUMN IF NOT EXISTS mime_type text;

-- Имена уникальны в обычных папках; личные деревья живут отдельно.
DROP INDEX IF EXISTS folders_parent_name_idx;
CREATE UNIQUE INDEX IF NOT EXISTS folders_parent_name_idx
    ON folders ((COALESCE(parent_id, 0)), lower(name))
    WHERE NOT is_personal;
CREATE UNIQUE INDEX IF NOT EXISTS folders_personal_root_idx
    ON folders (created_by)
    WHERE is_personal AND parent_id IS NULL;
CREATE INDEX IF NOT EXISTS folders_personal_idx ON folders (is_personal, created_by);
CREATE INDEX IF NOT EXISTS folders_parent_idx ON folders (parent_id);
CREATE INDEX IF NOT EXISTS changelog_published_idx ON changelog (is_published, published_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS transfers_expires_idx ON transfers (expires_at);
CREATE INDEX IF NOT EXISTS transfers_uploader_idx ON transfers (uploader_id, created_at DESC);
CREATE INDEX IF NOT EXISTS hosted_media_expires_idx ON hosted_media (expires_at);
CREATE INDEX IF NOT EXISTS hosted_media_uploader_idx ON hosted_media (uploader_id, created_at DESC);
CREATE INDEX IF NOT EXISTS files_folder_idx ON files (folder_id, uploaded_at DESC);

CREATE INDEX IF NOT EXISTS files_uploader_idx ON files (uploader_id);
CREATE INDEX IF NOT EXISTS files_order_idx ON files (is_pinned DESC, uploaded_at DESC);
CREATE INDEX IF NOT EXISTS file_tags_tag_idx ON file_tags (tag_id);
CREATE INDEX IF NOT EXISTS file_access_user_idx ON file_access (user_id);
CREATE INDEX IF NOT EXISTS user_tags_tag_idx ON user_tags (tag_id);
CREATE INDEX IF NOT EXISTS admin_rights_name_idx ON admin_rights (right_name);
CREATE INDEX IF NOT EXISTS app_releases_latest_idx ON app_releases (channel, published_at DESC, id DESC);

